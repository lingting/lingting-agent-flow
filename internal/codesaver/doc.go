// Package codesaver 把任务容器内的代码变更提交、推送到远程仓库，并按配置
// 尝试合并到基础分支。
//
// 边界：
//   - 所有 Git 操作都通过 ContainerExecutor 在目标任务容器内执行，不把容器内
//     代码复制到宿主机或本机数据目录后再提交；
//   - 容器归属与运行状态由 ContainerGuard 核验，本包不创建、不启动、不停止、
//     不删除容器，也不判断整个 Agent 任务是否成功；
//   - Commit、Push 与 Merge 的结果分别记录，Push 成功而 Merge 失败时任务分支
//     的保存状态仍然是成功；
//   - 默认不合并基础分支，只有显式授权时才执行合并；
//   - 不实现强制推送：远程历史冲突一律作为需要人工处理的状态返回；
//   - 不把凭据写入仓库 URL、Git 配置、命令行参数、日志或数据库普通字段。
//
// 本包不包含模型调用，也不实现工作流编排与调度。
package codesaver
